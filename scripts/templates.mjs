export function skeletonBody({ title, category }) {
  const sections = SECTIONS[category] ?? SECTIONS.sovety;
  const products = DEFAULT_PRODUCTS[category] ?? [];

  const lines = [];
  lines.push(
    `> ✏️ **Черновик-скелет — нужна вычитка перед публикацией.** Наполни каждый раздел ` +
      `конкретными советами, затем поставь \`draft: false\` во frontmatter. Удали эту заметку.`,
  );
  lines.push('');
  lines.push(`Вступление: зацепи читателя и скажи, чем поможет статья «${title}».`);
  lines.push('');
  for (const s of sections) {
    lines.push(`## ${s}`);
    lines.push('');
    lines.push(`_Напиши раздел «${s}» здесь._`);
    lines.push('');
  }
  return { body: lines.join('\n'), products };
}

/** Промпт для Claude API — просит написать готовую статью на русском. */
export function aiPrompt({ title, category, keywords = [] }) {
  return `Ты — опытный автор дружелюбного блога о кошках и собаках.

Напиши полную, оригинальную и по-настоящему полезную статью НА РУССКОМ ЯЗЫКЕ.

Заголовок: ${title}
Категория: ${category}
Ключевые слова для естественного упоминания: ${keywords.join(', ') || '(не заданы)'}

Требования:
- 700–1000 слов, ясный, тёплый и практичный русский для обычных читателей.
- Начни сразу с короткого цепляющего вступления (без «в этой статье»).
- Используй заголовки ## для разделов и списки, где уместно.
- Будь конкретным: реальные нормы кормления, частота ухода, признаки, сроки.
- Если тема касается здоровья — не ставь категоричных диагнозов и явно советуй
  обратиться к ветеринару при серьёзных или длительных симптомах.
- В конце добавь короткий раздел «## Коротко».
- НЕ вставляй заголовок как H1 (сайт добавит его сам).
- НЕ выдумывай статистику и названия брендов.
- Верни ТОЛЬКО тело статьи в markdown. Без frontmatter и без блоков кода.`;
}
